"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py

Варіант 1 (бібліотека): шість книжок, для кожної - анотація в корпусі,
термін видачі в днях із довідника і штраф за три дні затримки.
"""
import json
import re

# Беремо власні функції-інструменти з tools.py.
from tools import book_info, calculate

# Шість позицій. У варіанті 1 кожна позиція - назва книжки з каталогу.
ITEMS = [
    "Основи алгоритмів",
    "Місто вічної ночі",
    "Кулінарія для лінивих",
    "Таємниця старого будинку",
    "Таємниця зоряного неба",
    "Ремонт своїми руками",
]

# Питання для агента. У ньому має бути перелік усіх шести позицій.
QUESTION = (
    "Для кожної з шести книжок: Основи алгоритмів, Місто вічної ночі, "
    "Кулінарія для лінивих, Таємниця старого будинку, Таємниця зоряного неба, "
    "Ремонт своїми руками. Для кожної: (а) знайди в корпусі анотацію книжки "
    "(про що вона, її жанр та рівень складності) і наведи одним реченням; "
    "(б) знайди в довіднику термін видачі в днях та штраф за день прострочення; "
    "(в) порахуй штраф за три дні затримки. "
    "У кінці назви загальний штраф усіх шести книжок одним числом."
)

# Мінімум викликів інструментів для повного розв'язання: шість позицій по три інструменти.
MIN_CALLS = 18


def cost_of_one(title):
    """Штраф за три дні затримки однієї книжки: денний штраф із довідника, помножений на 3."""
    info = book_info(title)                             # інформація про книжку з довідника
    fine_per_day = float(re.search(r"штраф: (\d+)", info).group(1))
    return float(calculate("mul", fine_per_day, 3))     # множення через калькулятор


def compute():
    """Правильна відповідь: сума по всіх шести позиціях. Рахуємо самі, без моделі."""
    total = 0.0
    for title in ITEMS:
        total = total + cost_of_one(title)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),   # число як текст, без зайвих нулів: 142.5
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


task = save_task(compute())
print("Правильна відповідь:", task["expected"])
print("Файл long_task.json записано")
