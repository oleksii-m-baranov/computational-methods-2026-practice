import json
from providers import make_client

# Текст за темою "Кіно" (5 речень із числами для тесту на сумаризацію)
TEXT = (
    "Історія кінематографа веде відлік з 1895 року, коли брати Люм’єр влаштували перший платний показ фільму для 33 глядачів. "
    "До 1914 року середня тривалість стрічок зросла з 15 до 90 хвилин, започаткувавши еру повного метра. "
    "Перший у світі комерційний звуковий фільм дебютував на екранах у 1927 році і тривав 89 хвилин. "
    "Сьогодні міжнародний кінематографічний ринок випускає понад 7500 повнометражних кінокартин щороку. "
    "Найкасовіший фільм в історії зібрав понад 2923 мільйони доларів у світовому прокаті."
)

TASKS = {
    "1_fact": (
        "Рік першого публічного кінопоказу братів Люм’єр. "
        "Відповідай лише роком."
    ),
    "2_format": (
        "Згенеруй JSON із 3 історичних подій кіно з ключами: "
        '"event", "year", "city". Без пояснень, без markdown, лише JSON.'
    ),
    "3_summary": (
        f"Стисни наступний текст до двох речень, збережи всі числа:\n\n{TEXT}"
    ),
    "4_code": (
        "Напиши функцію на Python top_rated(films, n), яка приймає список словників "
        "з ключами 'title' та 'rating' і повертає n найкращих за рейтингом фільмів. "
        "Лише код."
    ),
    "5_logic": (
        "Зал 180 місць, сеанс 1 год 45 хв + 15 хв перерва, робота з 10:00 до 23:00. "
        "Скільки сеансів і глядачів? Покажи хід розв'язання."
    ),
    "6_language": (
        "Чим документальне кіно відрізняється від художнього? "
        "Поясни українською, два абзаци."
    ),
}

results = {}

for provider in ["local", "cloud"]:
    client, model = make_client(provider)
    results[model] = {}
    print(f"\n--- Запуск оцінки якості для {provider} ({model}) ---")

    for task_id, prompt in TASKS.items():
        answers = []
        for attempt in range(2):  # два прогони для перевірки детермінованості
            r = client.chat.completions.create(
                model=model,
                messages=[{"role": "user", "content": prompt}],
                temperature=0.7,
            )
            answers.append(r.choices[0].message.content)

        results[model][task_id] = answers
        print(f"{model} / {task_id} — готово")

with open("quality.json", "w", encoding="utf-8") as f:
    json.dump(results, f, ensure_ascii=False, indent=2)

