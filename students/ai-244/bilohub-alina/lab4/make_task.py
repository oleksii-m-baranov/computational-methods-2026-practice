"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py

Варіант 1 (бібліотека): шість книжок. Для кожної: (а) знайти її в корпусі,
(б) знайти в довіднику термін видачі і штраф за день, (в) порахувати штраф за три дні затримки.
"""
import json
import re

# Беремо власні функції-інструменти з tools.py
from tools import book_info, calculate

# Шість позицій: шість книжок (назви дослівно як у data/books.csv)
ITEMS = [
    "Мережі без таємниць",
    "Інженерія надійних систем",
    "Світло далеких маяків",
    "Місячний садівник",
    "Імперія солі та вітру",
    "Ремонт на балконі своїми руками",
]

DAYS_LATE = 3       # штраф рахуємо за три дні затримки

# Питання для агента. Список книжок підставляється з ITEMS, тож вони не розходяться.
# Маленька модель схильна завершувати довгу задачу завчасно, тому питання містить
# нумерований список і пряму заборону відповідати до опрацювання всіх шести книжок.
LIST_TEXT = " ".join(f"{n}. «{title}»;" for n, title in enumerate(ITEMS, start=1))
LIST_TEXT = LIST_TEXT[:-1] + "."

QUESTION = (
    "Опрацюй по черзі шість книжок: " + LIST_TEXT + " "
    "Для кожної книжки роби три виклики інструментів: (а) знайди її в корпусі; "
    "(б) знайди в довіднику термін видачі в днях і штраф за день; "
    "(в) порахуй штраф за три дні затримки: штраф за день, помножений на 3. "
    "Після третього виклику по книжці одразу переходь до наступної книжки зі списку. "
    "Роби один виклик інструмента за раз. "
    "Не давай фінальну відповідь, поки не опрацьовано всі шість книжок (разом 18 викликів). "
    "Лише після шостої книжки назви загальний штраф за всі шість книжок одним числом."
)

# Мінімум викликів інструментів для повного розв'язання: шість позицій по три інструменти.
MIN_CALLS = 18


def fine_per_day(title):
    """Штраф за день з довідника: беремо з тексту, який повертає book_info."""
    text = book_info(title)                                    # "... штраф: 12 грн/день"
    return float(re.search(r"штраф: (\d+(?:\.\d+)?)", text).group(1))


def cost_of_one(title):
    """Штраф за три дні затримки однієї книжки: штраф за день, помножений на 3 (через calculate)."""
    return float(calculate("mul", DAYS_LATE, fine_per_day(title)))


def compute():
    """Правильна відповідь: сума по всіх шести книжках. Рахуємо самі, без моделі."""
    total = 0.0
    for title in ITEMS:
        total = total + cost_of_one(title)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),   # число як текст, без зайвих нулів
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


task = save_task(compute())
print("Правильна відповідь:", task["expected"])
print("Файл long_task.json записано")
