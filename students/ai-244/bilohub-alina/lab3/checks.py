"""Перевірки змісту аргументів."""
import csv

with open("data/books.csv", encoding="utf-8") as f:
    TITLES = {row["title"].lower() for row in csv.DictReader(f)}


def check_meaning(name, args):
    if name == "search_books":
        if not args.query.strip():
            return ("Помилка: порожній пошуковий запит. "
                    "Передай жанр, тему або рівень складності одним-двома словами, "
                    "наприклад 'фантастика'.")

    if name == "book_info":
        # ключ довідника: назва має бути в data/books.csv
        # назв більше десяти, тому не перелічуємо їх, а кажемо, як дізнатися правильну
        if args.title.lower() not in TITLES:
            return (f"Помилка: книжки '{args.title}' немає в довіднику. "
                    "Точну назву можна дізнатися пошуком: виклич search_books "
                    "за темою або жанром і візьми назву з його результату. "
                    "Якщо пошук нічого не знайде, повідом користувачу, "
                    "що даних про цю книжку немає.")

    if name == "calculate":
        # правило з кількох аргументів: різниця не може бути від'ємною
        if args.operation == "sub" and args.a < args.b:
            return (f"Помилка: при відніманні {args.a} - {args.b} результат був би від'ємним. "
                    "Перший операнд має бути не менший за другий. "
                    "Перевір, які числа треба відняти, і виклич інструмент ще раз.")

    return None
