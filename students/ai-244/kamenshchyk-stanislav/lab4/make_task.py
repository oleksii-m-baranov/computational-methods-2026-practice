"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py

Варіант 8 (обслуговування авто): шість робіт, для кожної - опис у корпусі,
ціна роботи й деталі з прайсу і вартість з урахуванням кількості деталей.
"""
import json
import re

# Беремо власні функції-інструменти з tools.py
from tools import calc_total, price_info

# Шість позицій. У варіанті 8 кожна позиція - пара (робота, кількість деталей).
ITEMS = [("заміна масла", 4), ("заміна свічок запалювання", 4), ("заміна амортизаторів", 2),
         ("заміна передніх гальмівних колодок", 1), ("заміна гальмівної рідини", 2),
         ("заміна повітряного фільтра", 1)]

# Питання для агента. У ньому має бути перелік усіх шести позицій.
QUESTION = (
    "Для кожної з шести робіт: заміна масла, 4 деталі; заміна свічок запалювання, 4 деталі; "
    "заміна амортизаторів, 2 деталі; заміна передніх гальмівних колодок, 1 деталь; "
    "заміна гальмівної рідини, 2 деталі; заміна повітряного фільтра, 1 деталь. "
    "Для кожної: (а) знайди в описах робіт, яка ознака потреби в цій роботі, і наведи одним реченням; "
    "(б) знайди в прайсі вартість роботи й вартість однієї деталі; "
    "(в) порахуй вартість роботи з урахуванням вказаної кількості деталей. "
    "У кінці назви сумарну вартість усіх шести робіт одним числом."
)

# Мінімум викликів інструментів для повного розв'язання: шість позицій по три інструменти.
MIN_CALLS = 18


def prices_of(service):
    """Вартість роботи й однієї деталі з прайсу: дістаємо числа з тексту price_info."""
    text = price_info(service)
    work = float(re.search(r"Робота: ([\d.]+)", text).group(1))
    part = float(re.search(r"деталь: ([\d.]+)", text).group(1))
    return work, part


def cost_of_one(service, quantity):
    """Вартість однієї роботи: робота плюс деталі в потрібній кількості (через calc_total)."""
    work, part = prices_of(service)
    return float(calc_total(work, part, quantity).split(" грн")[0])


def compute():
    """Правильна відповідь: сума вартостей по всіх шести позиціях. Рахуємо самі, без моделі."""
    total = 0.0
    for service, quantity in ITEMS:
        total = total + cost_of_one(service, quantity)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),   # число як текст, без зайвих нулів
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


task = save_task(compute())
print("Правильна відповідь:", task["expected"])
print("Файл long_task.json записано")
