"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py

Варіант 7 (подорожі): шість відрізків маршруту, для кожного - опис місця з корпусу,
вартість проїзду з довідника і бюджет проїзду на групу заданої кількості осіб.
"""
import json

# Беремо власні функції-інструменти з tools.py.
from tools import calc_budget, find_route_info

# Шість позицій. У варіанті 7 кожна позиція - пара (маршрут, кількість осіб у групі).
ITEMS = [("Чернігів", 2), ("Затока", 4), ("Кам'янець-Подільський", 5),
         ("Софіївський парк", 10), ("Львів", 5), ("Коблево", 5)]

# Питання для агента. У ньому має бути перелік усіх шести позицій.
QUESTION = (
    "Для кожного з шести відрізків маршруту: Чернігів (2 особи), Затока (4 особи), "
    "Кам'янець-Подільський (5 осіб), Софіївський парк (10 осіб), Львів (5 осіб), "
    "Коблево (5 осіб). Для кожного: (а) знайди в описах маршрутів, що сказано про це місце, "
    "і наведи одним реченням; (б) знайди в довіднику транспорту вартість проїзду на одну особу; "
    "(в) порахуй бюджет проїзду для групи заданої кількості осіб без додаткових витрат. "
    "У кінці назви загальний бюджет усіх шести відрізків одним числом."
)

# Мінімум викликів інструментів для повного розв'язання: шість позицій по три інструменти.
MIN_CALLS = 18


def budget_of_one(route, people):
    """Бюджет проїзду групи на одному відрізку: вартість проїзду, помножена на кількість осіб."""
    price = find_route_info(route)[0]                      # вартість проїзду з довідника
    return float(calc_budget(price, people, 0).split()[0])  # "700.0 грн" -> 700.0, рахує калькулятор


def compute():
    """Правильна відповідь: сума по всіх шести позиціях. Рахуємо самі, без моделі."""
    total = 0.0
    for route, people in ITEMS:
        total = total + budget_of_one(route, people)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),   # число як текст, без зайвих нулів: 12200
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


task = save_task(compute())
print("Правильна відповідь:", task["expected"])
print("Файл long_task.json записано")
