from providers import make_client
import json

TEXT = """Пеніцилін був першим ефективним антибіотиком, відкритим Александром Флемінгом у 1928 році. Під час Другої світової війни в 1943 році було вироблено понад 21 мільярд доз цього препарату для лікування поранених. Загалом відкриття антибіотиків збільшило середню тривалість життя людини приблизно на 20 років. Сьогодні у світі існує більше 100 різних типів антибіотиків для боротьби з бактеріальними інфекціями. Використання пеніциліну дозволило знизити смертність від бактеріальної пневмонії з 90% до менш ніж 10%."""

TASKS = {
    "1_fact": "В якому році Александр Флемінг відкрив пеніцилін? Відповідай лише роком.",
    "2_format": "Створи JSON з полями discovery (назва відкриття), year (рік) та scientist (науковець) для відкриття пеніциліну. Без пояснень, без markdown, лише JSON.",
    "3_summary": "Стисни наступний текст до двох речень, збережи всі числа:\n\n" + TEXT,
    "4_code": "Напиши функцію bmi(weight_kg, height_m), яка розраховує індекс маси тіла та повертає його значення разом із категорією (наприклад: 'Норма', 'Надлишкова вага'). Лише код.",
    "5_logic": "У лікарні 40 пацієнтів, 18 з температурою, 15 з кашлем, 7 з обома симптомами. У скількох пацієнтів немає симптомів? Покажи хід розв'язання.",
    "6_language": "Чим вірус відрізняється від бактерії? Поясни українською, два абзаци.",
}

results = {}
for provider in ["local", "cloud"]:
    client, model = make_client(provider)
    results[model] = {}
    for task_id, prompt in TASKS.items():
        answers = []
        for attempt in range(2):  # два прогони на завдання
            r = client.chat.completions.create(
                model=model,
                messages=[{"role": "user", "content": prompt}],
                temperature=0.7,
            )
            answers.append(r.choices[0].message.content)
        results[model][task_id] = answers
        print(f"{model} / {task_id} — готово")

with open("quality.json", "w", encoding="utf-8") as f:
    json.dump(results, f, ensure_ascii=False, indent=2)