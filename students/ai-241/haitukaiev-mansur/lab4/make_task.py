"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py
Варіант 4 (тренування).
"""
import json

from tools import calc_calories, schedule_info

# Шість позицій: (заняття з розкладу, запит до корпусу, хвилини, коефіцієнт met).
ITEMS = [
    ("силове", "спина", 60, 6),
    ("кардіо", "ноги", 40, 8),
    ("йога", "прес", 50, 3),
    ("пілатес", "руки", 45, 3.5),
    ("розтяжка", "груди", 30, 2.5),
    ("силове", "просунутий", 75, 5),
]
WEIGHT_KG = 70

QUESTION = (
    "Для кожного з шести тренувань (вага людини 70 кг): "
    "1) заняття «силове», група м'язів спина, 60 хв, коефіцієнт навантаження 6; "
    "2) заняття «кардіо», група м'язів ноги, 40 хв, коефіцієнт 8; "
    "3) заняття «йога», група м'язів прес, 50 хв, коефіцієнт 3; "
    "4) заняття «пілатес», група м'язів руки, 45 хв, коефіцієнт 3.5; "
    "5) заняття «розтяжка», група м'язів груди, 30 хв, коефіцієнт 2.5; "
    "6) заняття «силове», рівень складності просунутий, 75 хв, коефіцієнт 5. "
    "Для кожного: (а) знайди в корпусі вправи за вказаною групою м'язів або рівнем "
    "(запит одним словом, наприклад «просунутий») і наведи назви одним реченням; "
    "(б) знайди в розкладі за назвою заняття день, час і тренера; "
    "(в) порахуй витрату калорій за заняття. "
    "У кінці назви сумарну витрату калорій за всі шість тренувань одним числом. "
    "Працюй строго по одному виклику інструмента за крок: зроби один виклик, "
    "дочекайся результату і лише потім роби наступний. "
    "У schedule_info завжди передавай назву заняття (силове, кардіо, йога, пілатес, розтяжка), "
    "а не групу м'язів чи рівень. "
    "Не давай відповіді, доки не виконаєш усі 18 викликів: для кожного з шести тренувань "
    "обов'язково потрібні search_exercises, schedule_info і calc_calories."
)

# Мінімум викликів інструментів: шість позицій по три інструменти.
MIN_CALLS = 18


def calories_of_one(activity, minutes, met):
    """Витрата калорій за одне заняття: рахуємо самі, тим самим інструментом."""
    if "немає в розкладі" in schedule_info(activity):
        raise ValueError(f"Заняття '{activity}' немає в schedule.csv")
    return int(calc_calories(minutes, WEIGHT_KG, met).split()[0])   # "441 ккал" -> 441


def compute():
    """Правильна відповідь: сума по всіх шести позиціях. Рахуємо самі, без моделі."""
    total = 0
    for activity, _query, minutes, met in ITEMS:
        total += calories_of_one(activity, minutes, met)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


task = save_task(compute())
print("Правильна відповідь:", task["expected"])
print("Файл long_task.json записано")