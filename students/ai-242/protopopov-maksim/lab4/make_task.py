"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py

Приклад нижче - для варіанта 3 (доставка). Для свого варіанта замініть:
імпорти, список ITEMS, текст QUESTION і функцію compute().
"""
import json
import re

# Беремо власні функції-інструменти з tools.py. ЗАМІНІТЬ на свої.
from tools import search_plants, fertilizer_info, calc_dose

# Шість позицій. У варіанті 3 кожна позиція - пара (рослина, об'єм горщика у літрах).
ITEMS = [("Фікус Бенджаміна", 5.0), ("Монстера Адансона", 3.0), ("Заміокулькас", 1.0),
         ("Сансевієрія трисмугова", 0.5), ("Ечеверія витончена", 0.3), ("Аспідістра висока", 1.5)]


# Питання для агента. У ньому має бути перелік усіх шести позицій.
QUESTION = (
    "Для кожної з шести рослин: Фікус Бенджаміна (горщик 5 л), Монстера Адансона (3 л), Заміокулькас (1 л), "
    "Сансевієрія трисмугова (0.5 л), Ечеверія витончена (0.3 л), Аспідістра висока (1.5 л). Для кожної: (а) знайди в корпусі "
    "поради з догляду за рослиною і наведи одним реченням; (б) знайди в довіднику "
    "періодичність підживлення; (в) порахуй дозу добрива для горщика заданого "
    "об'єму. У кінці назви сумарну дозу добрива для всіх шести рослин у мл одним числом."
)

# Мінімум викликів інструментів для повного розв'язання: шість позицій по три інструменти.
MIN_CALLS = 18


def number_from(text):
    """Перше число з тексту: з 'Доза: 5 мл на літр...' дістає 5."""
    return float(re.search(r"\d+(?:\.\d+)?", text).group())


def dose_of_one(plant, liters):
    """Доза для однієї рослини: ті самі три кроки, що має зробити агент."""
    found = search_plants(plant)                       # (а) пошук у корпусі
    assert "нічого не знайдено" not in found, f"У корпусі немає: {plant}"
    info = fertilizer_info(plant)                      # (б) довідник
    assert "немає в довіднику" not in info, f"У довіднику немає: {plant}"
    per_liter = number_from(info)                      # перше число - це доза мл на літр
    return number_from(calc_dose(liters, per_liter))   # (в) 'N мл' -> N


def compute():
    """Правильна відповідь: сума по шести рослинах. Рахуємо без моделі."""
    total = 0.0
    for plant, liters in ITEMS:
        total += dose_of_one(plant, liters)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),   # число як текст, без зайвих нулів: 142.5
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


task = save_task(compute())
print("Правильна відповідь:", task["expected"])
print("Файл long_task.json записано")