from providers import make_client
import json

TEXT = """За 2015 рік загальний пасажирообіг на внутрішніх і міжнародних рейсах становив 
4,6 млн осіб. За 2015 рік повітряним транспортом було перевезено 37,7 млн тонно-кілометрів вантажів 
(без врахування багажу пасажирів). Літаками в Україні перевозять переважно пасажирів. 
За середньою відстанню перевезення одного пасажира повітряний транспорт в Україні посідає перше місце 
і перевищує залізничний транспорт більш, як у 10 разів. Пасажирським перевезенням в Україні 
характерна сезонність. Основний пасажиропотік припадає на літо. Діють повітряні лінії до Франкфурта, 
Парижа, Торонто, Нью-Йорка, Лондона, Тель-Авіва. Розширюються зв'язки з країнами Близького Сходу, 
Китаєм."""

TASKS = {
    "1_fact":     "<Рік відкриття Київського метрополітену>. Відповідай лише роком.",
    "2_format":   "<JSON: city, year, lines_count для Київського метро>. Без пояснень, без markdown, лише JSON.",
    "3_summary":  "Стисни наступний текст до двох речень, збережи всі числа:\n\n" + TEXT,
    "4_code":     "total_weight(items) — сума ваг зі списку словників>. Лише код.",
    "5_logic":    "120 ящиків: 45 по 8 кг, решта по 12 кг. Вантажівка тримає 1200 кг. Скільки рейсів?>. Покажи хід розв'язання.",
    "6_language": "Чим контейнерне перевезення відрізняється від навалочного>. Поясни українською, два абзаци.",
}

results = {}

for provider in ["local", "local2", "cloud"]:
    client, model = make_client(provider)
    results[model] = {}
    for task_id, prompt in TASKS.items():
        answers = []
        for attempt in range(2):          # два прогони на завдання
            r = client.chat.completions.create(
                model=model,
                messages=[{"role": "user", "content": prompt}],
                temperature=0.7,
            )
            answers.append(r.choices[0].message.content)
        results[model][task_id] = answers
        print(f"{model} / {task_id} — готово")

with open("quality.json", "w", encoding="utf-8") as f:
    json.dump(results, f, ensure_ascii=False, indent=2)