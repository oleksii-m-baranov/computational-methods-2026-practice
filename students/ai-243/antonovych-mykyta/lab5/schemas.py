SCHEMAS = []

for name in config.ALLOWED:

    SCHEMAS.append({
        "type": "function",
        "function": {
            "name": name,
            "description": (RAG_DESCRIPTIONS[config.DOCS_DESCRIPTION]
                            if name == "search_docs" else DESCRIPTIONS[name]),
            "parameters": ARGS[name].model_json_schema(),
        },
    })


def set_description(name, text):
    for schema in SCHEMAS:
        if schema["function"]["name"] == name:
            schema["function"]["description"] = text
            return
    raise KeyError(name)
