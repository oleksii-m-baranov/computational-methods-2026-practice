"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py

Варіант 7 (подорожі): шість відрізків маршруту; для кожного - опис із корпусу,
вартість проїзду з довідника і бюджет для групи заданого розміру.
"""
import json

# Беремо власні функції-інструменти з tools.py.
from tools import calc_budget, find_route_price

# Шість позицій. У варіанті 7 кожна позиція - пара (маршрут, кількість осіб у групі).
ITEMS = [("Кам'янець-Подільський", 3), ("Хотин", 2), ("Одеса", 4),
         ("Карпати", 3), ("Шацькі озера", 2), ("Львів", 5)]

# Питання для агента. У ньому має бути перелік усіх шести позицій.
QUESTION = (
    "Для кожного з шести відрізків маршруту: Кам'янець-Подільський (3 особи), Хотин (2 особи), "
    "Одеса (4 особи), Карпати (3 особи), Шацькі озера (2 особи), Львів (5 осіб). "
    "Для кожного: (а) знайди в корпусі опис маршруту і наведи його одним реченням; "
    "(б) знайди в довіднику вартість проїзду на одну особу; "
    "(в) порахуй бюджет поїздки для вказаної кількості осіб (додаткових витрат немає). "
    "У кінці назви загальний бюджет усіх шести поїздок одним числом."
)

# Мінімум викликів інструментів для повного розв'язання: шість позицій по три інструменти.
MIN_CALLS = 18


def cost_of_one(route, people):
    """Бюджет поїздки однієї групи: ціна з довідника, помножена на кількість осіб, extra = 0."""
    price = find_route_price(route)                      # ціна проїзду з довідника
    return float(calc_budget(price, people, 0).split()[0])   # множення через калькулятор («1260.0 грн»)


def compute():
    """Правильна відповідь: сума по всіх шести позиціях. Рахуємо самі, без моделі."""
    total = 0.0
    for route, people in ITEMS:
        total = total + cost_of_one(route, people)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),   # число як текст, без зайвих нулів: 142.5
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


if __name__ == "__main__":
    task = save_task(compute())
    print("Правильна відповідь:", task["expected"])
    print("Файл long_task.json записано")
