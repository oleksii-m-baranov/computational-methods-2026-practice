def set_description(name, text):
    """Підміняє опис інструмента в схемах для поточного тестового прогону."""
    for item in SCHEMAS:
        if item["function"]["name"] == name:
            item["function"]["description"] = text
            return
    raise ValueError(f"Інструмент {name!r} відсутній у SCHEMAS")
