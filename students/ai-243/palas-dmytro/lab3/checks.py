"""Перевірки змісту аргументів."""
import csv

with open("data/materials.csv", encoding="utf-8") as f:
    MATERIALS = [row["material"].lower() for row in csv.DictReader(f)]


def check_meaning(name, args):
    if name == "search_works":
        if not args.query.strip():
            return (
                "Помилка: пошуковий запит не може бути порожнім. "
                "Передай одне-два слова українською (тип роботи або категорію), "
                "виправ аргумент і виклич інструмент ще раз."
            )

    if name == "material_info":
        if args.material.lower() not in MATERIALS:
            return (
                f"Помилка: матеріалу '{args.material}' немає в довіднику. "
                "У довіднику записані лише базові назви матеріалів у нижньому регістрі без одиниці виміру "
                "(без слів 'рулон', 'мішок', 'банка', 'упаковка', 'лист', наприклад 'ламінат' замість 'упаковка ламінату'). "
                "Якщо у запиті було зайве слово або неточна форма — виправ аргумент і виклич інструмент ще раз. "
                "Якщо ж такого матеріалу немає в асортименті — повідом користувачу."
            )
    return None
