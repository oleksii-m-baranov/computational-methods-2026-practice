"""Створює long_task.json: довге питання, правильну відповідь і мінімум викликів.

Запуск:  python make_task.py

Варіант 6 (ремонт квартири): шість матеріалів, для кожного - пошук роботи в корпусі,
ціна за одиницю з довідника, кількість за площею і вартість.
"""
import json
import re

# Беремо власні функції-інструменти з tools.py
from tools import calc_materials, material_info

# Шість позицій. У варіанті 6 кожна позиція - пара (матеріал, площа в м²).
ITEMS = [("шпалери", 18), ("водоемульсійна фарба", 18), ("настінна плитка", 5),
         ("ламінат", 18), ("лінолеум", 18), ("гідроізоляційна мастика", 4)]

# Питання для агента. У ньому має бути перелік усіх шести позицій.
QUESTION = (
    "Для кожного з шести матеріалів: шпалери 18 м², водоемульсійна фарба 18 м², "
    "настінна плитка 5 м², ламінат 18 м², лінолеум 18 м², гідроізоляційна мастика 4 м². "
    "Для кожного: (а) знайди в корпусі робіт, у якій роботі використовується матеріал, "
    "і наведи одним реченням; (б) знайди в довіднику ціну за одиницю; "
    "(в) порахуй кількість одиниць на задану площу і вартість. "
    "У кінці назви загальну вартість усіх шести матеріалів одним числом."
)

# Мінімум викликів інструментів для повного розв'язання: шість позицій по три інструменти.
MIN_CALLS = 18


def cost_of_one(material, area):
    """Вартість одного матеріалу: кількість одиниць на площу, помножена на ціну."""
    info = material_info(material)                                      # ціна й покриття з довідника
    price = float(re.search(r"ціна: ([\d.]+) грн", info).group(1))
    coverage = float(re.search(r"покриття: ([\d.]+) м²", info).group(1))
    result = calc_materials(area, coverage, price)                      # кількість і вартість
    return float(re.search(r"вартість: ([\d.]+) грн", result).group(1))


def compute():
    """Правильна відповідь: сума по всіх шести позиціях. Рахуємо самі, без моделі."""
    total = 0.0
    for material, area in ITEMS:
        total = total + cost_of_one(material, area)
    return total


def save_task(total):
    """Записує питання, правильну відповідь і MIN_CALLS у файл long_task.json."""
    task = {
        "id": "L1",
        "question": QUESTION,
        "expected": format(round(total, 2), "g"),   # число як текст, без зайвих нулів
        "min_calls": MIN_CALLS,
    }
    with open("long_task.json", "w", encoding="utf-8") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    return task


task = save_task(compute())
print("Правильна відповідь:", task["expected"])
print("Файл long_task.json записано")
