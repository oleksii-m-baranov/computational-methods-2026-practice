# Автоматичне формування схем із Pydantic-моделей
SCHEMAS = []

for name in config.ALLOWED:
    if name not in ARGS:
        raise KeyError(
            f"Для інструмента '{name}' немає моделі в arguments.py"
        )

    if name not in DESCRIPTIONS:
        raise KeyError(
            f"Для інструмента '{name}' немає опису в schemas.py"
        )

    description = DESCRIPTIONS[name]

    if name == "search_docs":
        variant = getattr(config, "DOCS_DESCRIPTION", "B")
        description = RAG_DESCRIPTIONS[variant]

    SCHEMAS.append({
        "type": "function",
        "function": {
            "name": name,
            "description": description,
            "parameters": ARGS[name].model_json_schema(),
        },
    })
