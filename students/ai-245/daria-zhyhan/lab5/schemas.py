def build_schemas():
    schemas = []
    for name in config.ALLOWED:
        desc = SEARCH_DOCS_VARIANTS[config.DOCS_DESCRIPTION] if name == "search_docs" else DESCRIPTIONS[name]
        schemas.append({
            "type": "function",
            "function": {
                "name": name,
                "description": desc,
                "parameters": ARGS[name].model_json_schema(),
            },
        })
    return schemas


SCHEMAS = build_schemas()